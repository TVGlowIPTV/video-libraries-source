#!/usr/bin/env python3
"""Proves that no GPL file of zvbi is compiled into TVGlow's libzvbi.a.

Run in Linux/WSL after the libzvbi step of build.sh:

    python3 check_zvbi_licences.py <zvbi build-in-source dir> <libzvbi.a>

For every object in the static library (`ar t`), it reads the dependency
file the compiler wrote for that object (`src/.deps/<object>.Plo`), so it
covers each compiled source file and every header that source included.
Every zvbi file found that way is classified by its own licence header,
then by zvbi's COPYING.md where a file has no header. Files from outside
the zvbi tree (MinGW and libiconv headers) are listed but not classified:
they are system headers or come from libraries already in the DLL.

Exits 1 if any zvbi file is GPL-only, GPL-2+ or unclassified, if any of the
files TVGlow's patch removes is still compiled, or if an object has no
dependency file.
"""
import os
import re
import subprocess
import sys

REMOVED = {"src/packet-830.c", "src/packet-830.h", "src/pdc.c", "src/pdc.h", "src/exp-vtx.c"}
# COPYING.md entries for files without their own header (zvbi v0.2.46).
COPYING = [
    (re.compile(r"^src/(packet-830|pdc)\."), "GPL-2"),
    (re.compile(r"^src/ure\."), "MIT"),
    (re.compile(r"^src/videodev2k\.h$"), "GPL-2+ or BSD-3-Clause"),
    (re.compile(r"^src/strptime\."), "LGPL-2.1+"),
    (re.compile(r"^src/dvb/(dmx|frontend)\.h$"), "LGPL-2.1+"),
    (re.compile(r"^src/"), "LGPL-2+"),
]
# Files generated by the build: configure's output carries no licence text.
GENERATED = {"config.h": "generated by configure (autoconf output)"}
# configure.ac writes site_def.h at the top level, where COPYING.md's default
# (GPL-2+) would apply. It is accepted only while, comments removed, it holds
# nothing but its include guard, so no code or data from it is compiled.
GUARD_ONLY = {"site_def.h": ["#ifndef SITE_DEF_H", "#define SITE_DEF_H", "#endif"]}


def header_licence(path):
    with open(path, encoding="utf-8", errors="replace") as handle:
        head = "".join(handle.readlines()[:80])
    text = re.sub(r"\s+", " ", head)
    if re.search(r"GNU (Lesser|Library) General Public", text):
        return "LGPL (header)"
    if "GNU General Public License" in text:
        if re.search(r"\bor\b.{0,80}\bBSD\b|\bBSD\b.{0,80}\bor\b", text):
            return "GPL or BSD dual (header)"
        return "GPL (header)"
    if re.search(r"Permission is hereby granted|Redistribution and use in source", text):
        return "permissive (header)"
    return None


def classify(rel, path):
    if rel in GENERATED:
        return GENERATED[rel], True
    if rel in GUARD_ONLY:
        with open(path, encoding="utf-8", errors="replace") as handle:
            code = re.sub(r"/\*.*?\*/", "", handle.read(), flags=re.S)
        lines = [line.strip() for line in code.splitlines() if line.strip()]
        if lines == GUARD_ONLY[rel]:
            return "written by configure; include guard only, no code", True
        return "written by configure but holds code: " + "; ".join(lines), False
    found = header_licence(path)
    if found is None:
        for pattern, licence in COPYING:
            if pattern.search(rel):
                found = licence + " (COPYING.md)"
                break
    if found is None:
        return "unclassified", False
    ok = ("GPL" not in found.replace("LGPL", "")) or "BSD" in found
    return found, ok


def main():
    source = os.path.realpath(sys.argv[1])
    archive = sys.argv[2]
    ar = os.environ.get("AR", "x86_64-w64-mingw32-ar")
    members = subprocess.run([ar, "t", archive], check=True, capture_output=True,
                             text=True).stdout.split()
    failures = []
    zvbi_files = {}
    outside = set()
    print(f"libzvbi.a members: {len(members)}")
    for member in members:
        stem = member[:-2] if member.endswith(".o") else member
        dep = os.path.join(source, "src", ".deps", stem + ".Plo")
        if not os.path.exists(dep):
            failures.append(f"{member}: no dependency file {dep}")
            continue
        with open(dep, encoding="utf-8") as handle:
            body = handle.read().replace("\\\n", " ")
        rule = body.split("\n", 1)[0]  # the first rule; later lines are phony targets
        paths = rule.split(":", 1)[1].split()
        source_file = None
        for item in paths:
            full = os.path.realpath(os.path.join(source, "src", item))
            if full.startswith(source + os.sep):
                rel = os.path.relpath(full, source).replace(os.sep, "/")
                zvbi_files.setdefault(rel, set()).add(member)
                if source_file is None and rel.endswith(".c"):
                    source_file = rel
            else:
                outside.add(full)
        print(f"  {member:32} <- {source_file}")
    print(f"\nzvbi files compiled into the archive (sources and headers): {len(zvbi_files)}")
    for rel in sorted(zvbi_files):
        licence, ok = classify(rel, os.path.join(source, rel))
        if rel in REMOVED:
            ok = False
            licence += "; removed by TVGlow's patch but still compiled"
        print(f"  {'ok  ' if ok else 'FAIL'} {rel:28} {licence}")
        if not ok:
            failures.append(f"{rel}: {licence}")
    roots = sorted({re.sub(r"/(include|lib)/.*$", r"/\1", p) for p in outside})
    print(f"\nheaders from outside the zvbi tree: {len(outside)}, under {', '.join(roots)}")
    if failures:
        print("\nRESULT: FAIL")
        for failure in failures:
            print("  " + failure)
        return 1
    print("\nRESULT: PASS - no GPL-only or GPL-2+ zvbi file is compiled into libzvbi.a")
    return 0


if __name__ == "__main__":
    sys.exit(main())
